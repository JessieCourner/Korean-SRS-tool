for path in glob.glob("unit*.json"):
    text = open(path, encoding="utf-8").read()
    for old, new in replacements.items():
        text = text.replace(old, new)
    if path.endswith("unit0_1_lessons_0_25.json"):
        import json
        payload = json.loads(text)
        for lesson in payload["lessons"]:
            hints = unit0_hints.get(lesson["lesson_number"])
            if not hints:
                continue
            for card, hint in zip(lesson["cards"], hints):
                card["hint"] = f"Начальная форма: {hint}"
        text = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    text = text.replace("Начальная форма:", "Base form:")
    open(path, "w", encoding="utf-8").write(text)
